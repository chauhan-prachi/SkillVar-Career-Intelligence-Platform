#!/bin/bash
# Regenerates docs/VERIFICATION.md from real command output. Run from the repo root with the venv active and PostgreSQL running.
set -u
OUT=docs/VERIFICATION.md
run() { local title="$1"; shift; echo; echo "### $title"; echo '```'; "$@" 2>&1 | grep -v "AXES: BEGIN" | tail -${TAILN:-12}; echo '```'; }
{
echo "# Verification report"; echo
echo "Generated by \`scripts/make_verification_report.sh\` on $(date -u +%Y-%m-%dT%H:%MZ) (UTC). Output is verbatim."
echo "Environment: $(python --version 2>&1), $(uname -sr). **Not verified on Windows.**"
TAILN=3 run "Database server and driver" python manage.py shell -c "from django.db import connection as c; c.ensure_connection(); import psycopg; print('PostgreSQL', c.pg_version, '| psycopg', psycopg.__version__, '| django', __import__('django').get_version())"
TAILN=2 run "pip check" python -m pip check
TAILN=4 run "pytest (full suite)" python -m pytest
TAILN=2 run "ruff" ruff check .
TAILN=2 run "manage.py check" python manage.py check
TAILN=2 run "makemigrations --check" python manage.py makemigrations --check --dry-run
TAILN=6 run "manage.py check --deploy (DEBUG=0, generated strong key)" env DEBUG=0 SECRET_KEY=$(python -c "import secrets;print(secrets.token_urlsafe(60))") python manage.py check --deploy
} > $OUT
echo "wrote $OUT"
